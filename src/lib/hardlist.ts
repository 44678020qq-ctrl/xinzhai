/**
 * Hard List 拦截检查
 * 在 AI 生成之前调用，命中即返回拒答模板
 */
export function checkHardList(message: string): HardListResult {
  const trimmed = message.trim();
  
  for (const item of HARD_LIST_PATTERNS) {
    // 关键词检查
    const keywordHit = item.keywords.some(kw => trimmed.includes(kw));
    // 正则检查
    const patternHit = item.patterns.some(p => p.test(trimmed));
    
    if (keywordHit || patternHit) {
      return {
        blocked: true,
        category: item.category,
        reply: REFUSAL_TEMPLATES[item.category],
      };
    }
  }
  
  return { blocked: false };
}